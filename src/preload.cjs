const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setConfig: (patch) => ipcRenderer.invoke('settings:setConfig', patch),
  chooseWorkspace: () => ipcRenderer.invoke('workspace:choose'),
  setWorkspace: (dir) => ipcRenderer.invoke('workspace:set', dir),
  revealWorkspace: () => ipcRenderer.invoke('workspace:reveal'),
  setProjectIcon: (key, icon) => ipcRenderer.invoke('project:setIcon', key, icon),
  setProjectName: (dir, name) => ipcRenderer.invoke('project:setName', dir, name),
  setProjectOrder: (keys) => ipcRenderer.invoke('project:setOrder', keys),
  setProjectHidden: (dir, hidden) => ipcRenderer.invoke('project:setHidden', dir, hidden),
  pickProjectIcon: (key) => ipcRenderer.invoke('project:pickIcon', key),
  deleteProject: (dir) => ipcRenderer.invoke('project:delete', dir),
  providerModels: () => ipcRenderer.invoke('providers:models'),
  addProvider: (server) => ipcRenderer.invoke('providers:add', server),
  updateProvider: (id, patch) => ipcRenderer.invoke('providers:update', id, patch),
  removeProvider: (id) => ipcRenderer.invoke('providers:remove', id),
  engineStatus: () => ipcRenderer.invoke('engine:status'),
  setModelContext: (model, numCtx) => ipcRenderer.invoke('engine:setContext', model, numCtx),
  setEngineOptions: (patch) => ipcRenderer.invoke('engine:setOptions', patch),
  send: (text, turnId) => ipcRenderer.invoke('agent:send', text, turnId),
  rewind: (turnId) => ipcRenderer.invoke('agent:rewind', turnId),
  resumeFrom: (actId) => ipcRenderer.invoke('agent:resumeFrom', actId),
  stop: () => ipcRenderer.invoke('agent:stop'),
  reset: () => ipcRenderer.invoke('agent:reset'),
  newOffProject: () => ipcRenderer.invoke('conversations:newOffProject'),
  approve: (id, ok, always, reason) => ipcRenderer.invoke('agent:approve', { id, ok, always, reason }),
  onEvent: (fn) => ipcRenderer.on('agent:event', (_, ev) => fn(ev)),
  onApproval: (fn) => ipcRenderer.on('agent:approval', (_, req) => fn(req)),

  currentSession: () => ipcRenderer.invoke('session:current'),
  listConversations: () => ipcRenderer.invoke('conversations:list'),
  openConversation: (id) => ipcRenderer.invoke('conversations:open', id),
  renameConversation: (id, title) => ipcRenderer.invoke('conversations:rename', id, title),
  deleteConversation: (id) => ipcRenderer.invoke('conversations:delete', id),
  markConversationsRead: (ids) => ipcRenderer.invoke('conversations:markRead', ids),
  onConversationsChanged: (fn) => ipcRenderer.on('conversations:changed', (_, id) => fn(id)),
  onSessionsChanged: (fn) => ipcRenderer.on('sessions:changed', () => fn()),
  onRenameConversation: (fn) => ipcRenderer.on('ui:renameConversation', () => fn()),
  claudeStatus: () => ipcRenderer.invoke('claude:status'),
  setChoice: (patch) => ipcRenderer.invoke('session:setChoice', patch),
  listSkills: () => ipcRenderer.invoke('skills:list'),
  setDraft: (text) => ipcRenderer.invoke('session:setDraft', text),
  onOpenSettings: (fn) => ipcRenderer.on('ui:openSettings', () => fn()),
  onContextMenu: (fn) => ipcRenderer.on('ui:contextMenu', (_, p) => fn(p)),
  onSwipe: (fn) => ipcRenderer.on('ui:swipe', (_, direction) => fn(direction)),
  edit: (cmd, arg) => ipcRenderer.invoke('ui:edit', cmd, arg),

  getMemory: () => ipcRenderer.invoke('memory:get'),
  setMemory: (notes) => ipcRenderer.invoke('memory:set', notes),
  getSteps: () => ipcRenderer.invoke('steps:get'),
  setSteps: (steps) => ipcRenderer.invoke('steps:set', steps),
  getSystemPrompt: () => ipcRenderer.invoke('prompt:get'),
  setSystemPrompt: (text) => ipcRenderer.invoke('prompt:set', text),

  checkTor: () => ipcRenderer.invoke('tor:check'),
  torStatus: () => ipcRenderer.invoke('tor:status'),
  torNewCircuits: () => ipcRenderer.invoke('tor:newnym'),
  getContext: () => ipcRenderer.invoke('context:get'),
  compactContext: () => ipcRenderer.invoke('context:compact'),

  listFiles: (rel) => ipcRenderer.invoke('files:list', rel),
  readFile: (rel) => ipcRenderer.invoke('files:read', rel),
  openFileExternal: (rel) => ipcRenderer.invoke('files:openExternal', rel),
  revealFile: (rel) => ipcRenderer.invoke('files:reveal', rel),

  gitStatus: () => ipcRenderer.invoke('git:status'),
  gitDiff: (file, opts) => ipcRenderer.invoke('git:diff', file, opts),
  gitFetch: () => ipcRenderer.invoke('git:fetch'),
  gitSync: () => ipcRenderer.invoke('git:sync'),
  gitConnect: (url) => ipcRenderer.invoke('git:connect', url),
  gitRemote: (dir) => ipcRenderer.invoke('git:remote', dir),
  gitSetRemote: (dir, url) => ipcRenderer.invoke('git:setRemote', dir, url),
  gitRemoveRemote: (dir) => ipcRenderer.invoke('git:removeRemote', dir),
  githubStatus: () => ipcRenderer.invoke('github:status'),
  githubOpenTokenPage: () => ipcRenderer.invoke('github:openTokenPage'),
  githubSetToken: (token) => ipcRenderer.invoke('github:setToken', token),
  githubRemoveToken: () => ipcRenderer.invoke('github:removeToken'),
  gitCreateGithub: (repo) => ipcRenderer.invoke('git:createGithub', repo),
});
